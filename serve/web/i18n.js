// ------------------------------------------------------------------ the current language
let LANG = "en";
let LOCALE = "en";

// ?lang= wins once (a shortcut, and how the manual checks switch), then the saved choice, then the browser
function detectLang() {
  try {
    const q = new URLSearchParams(location.search).get("lang");
    if (q === "en" || q === "zh") return q;
  } catch (e) { /* a URL this browser can't parse: fall through */ }
  try {
    const raw = localStorage.getItem("strata.lang");
    if (raw !== null) {
      let v = raw;
      try { v = JSON.parse(raw); } catch (e) { /* an older hand-written value: use it as-is */ }
      if (v === "en" || v === "zh") return v;
    }
  } catch (e) { /* private mode: nothing saved, the browser decides */ }
  return String(navigator.language || "en").toLowerCase().startsWith("zh") ? "zh" : "en";
}

// t("pill.reading", {pct: 42}) -> the whole sentence in the current language.
// A missing zh entry falls back to English; a key in neither dictionary comes back as itself (and says so once).
function t(key, params) {
  let s = STRATA_I18N[LANG] ? STRATA_I18N[LANG][key] : undefined;
  if (s === undefined) s = STRATA_I18N.en[key];
  if (s === undefined) {
    console.warn("strata i18n: no entry for " + key);
    return key;
  }
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] === undefined ? m : String(params[k])));
  return s;
}
// the _one / _other pair for a count
function tn(key, n, params) {
  return t(key + (n === 1 ? "_one" : "_other"), Object.assign({n}, params || {}));
}

// the static skeleton: index.html keeps its English text, so a missing entry falls back without JS help
function applyLang() {
  document.documentElement.lang = LANG;
  LOCALE = STRATA_LOCALES[LANG] || "en";
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.getAttribute("data-i18n"));
  for (const el of document.querySelectorAll("[data-i18n-title]")) el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  for (const el of document.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  for (const el of document.querySelectorAll("[data-i18n-placeholder]")) el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  updateLangControls();
}

// the header button and the About segment show the language you are in
function updateLangControls() {
  const btn = document.getElementById("lang-btn");
  if (btn) {
    btn.textContent = LANG === "zh" ? "EN" : "中文";
    btn.setAttribute("aria-label", t("lang.aria"));
    btn.title = LANG === "zh" ? "English" : "中文";
  }
  for (const b of document.querySelectorAll("#lang-seg button")) b.setAttribute("aria-checked", String(b.dataset.v === LANG));
}

function setLang(lang, save = true) {
  if (lang !== "en" && lang !== "zh") lang = detectLang();      // an unknown value: back to the default rule
  LANG = lang;
  if (save) {
    try { localStorage.setItem("strata.lang", JSON.stringify(lang)); } catch (e) { /* private mode: this visit only */ }
  }
  applyLang();
  if (typeof window.strataRedraw === "function") window.strataRedraw();
}

